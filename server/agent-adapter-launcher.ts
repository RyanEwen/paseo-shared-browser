import { readFile, rename, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { resolveBrowserRuntimeRoot } from "./runtime-path";

const LAUNCHER_FILE = "shared-browser-mcp.cjs";
const ADAPTER_FILE = "shared-browser-mcp.cjs";
const FILE_MODE = 0o600;
/** The supervisor endpoint file, relative to the plugin-data root (see `resolveSupervisorPaths`). */
const ENDPOINT_RELATIVE_PATH = "supervisor-v2/runtime.json";

/**
 * Paseo saves each agent's MCP server command, including its absolute script path, when the
 * agent is created. Pointing that path into an immutable runtime directory pins the agent to the
 * adapter that was current at creation, which a later supervisor may not speak. This launcher
 * lives at a fixed path beside the runtime pointer. When the session starts it loads the adapter
 * the running supervisor published, so an install that moved the pointer before its supervisor
 * replacement cannot hand agents a newer adapter; with no supervisor running it follows the
 * pointer, whose supervisor the plugin will start.
 *
 * The source is version-independent: rewriting it never changes behaviour for running agents.
 * Its pointer rules mirror `resolveBrowserRuntimeRoot`.
 */
const LAUNCHER_SOURCE = `"use strict";
// Generated by the Shared Browser plugin. Do not edit; it is rewritten on plugin start.
// Loads the agent adapter that matches the running supervisor, or the current runtime's.
const { existsSync, readFileSync } = require("node:fs");
const { basename, dirname, join } = require("node:path");

const RUNTIME_DIRECTORY = /^\\.runtime-[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/u;

function adapterIn(directory) {
  return join(__dirname, directory, ${JSON.stringify(ADAPTER_FILE)});
}

function isAlive(pid) {
  if (!Number.isSafeInteger(pid) || pid <= 0) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return Boolean(error && error.code === "EPERM");
  }
}

// A running supervisor publishes its own adapter and pid. An endpoint left by a crashed
// supervisor is ignored. Only the runtime directory name is taken from the endpoint and it is
// resolved under this plugin-data root, so the file can never redirect the launcher elsewhere
// (and symlinked homes, where published and resolved paths differ, still match).
function runningSupervisorAdapter() {
  let endpoint;
  try {
    endpoint = JSON.parse(readFileSync(join(__dirname, ${JSON.stringify(ENDPOINT_RELATIVE_PATH)}), "utf8"));
  } catch {
    return null;
  }
  if (!endpoint || typeof endpoint.adapter !== "string" || !isAlive(endpoint.pid)) return null;
  const directory = basename(dirname(endpoint.adapter));
  if (!RUNTIME_DIRECTORY.test(directory)) return null;
  const adapter = adapterIn(directory);
  return existsSync(adapter) ? adapter : null;
}

function currentRuntimeAdapter() {
  let directory;
  try {
    directory = readFileSync(join(__dirname, "runtime-current"), "utf8").trim();
  } catch (error) {
    if (error && error.code === "ENOENT") return adapterIn("runtime");
    throw error;
  }
  if (!RUNTIME_DIRECTORY.test(directory)) throw new Error("Shared Browser runtime pointer is invalid");
  return adapterIn(directory);
}

require(runningSupervisorAdapter() ?? currentRuntimeAdapter());
`;

/** The plugin-data directory that holds the runtime pointer and the launcher. */
function pluginDataRoot(paseoHome: string): string {
  return join(paseoHome, "plugin-data", "shared-browser");
}

/**
 * Write the stable launcher if it is missing or differs, replacing it atomically so a concurrently
 * starting agent never reads a partial file.
 *
 * @param paseoHome The daemon's Paseo home directory.
 * @returns The absolute launcher path to save in new agents' MCP configuration.
 */
export async function ensureAgentAdapterLauncher(paseoHome: string): Promise<string> {
  const launcherPath = join(pluginDataRoot(paseoHome), LAUNCHER_FILE);
  const existing = await readFile(launcherPath, "utf8").catch(() => null);
  if (existing === LAUNCHER_SOURCE) return launcherPath;

  const pendingPath = `${launcherPath}.${process.pid}.pending`;
  try {
    await writeFile(pendingPath, LAUNCHER_SOURCE, { mode: FILE_MODE });
    await rename(pendingPath, launcherPath);
  } finally {
    await rm(pendingPath, { force: true });
  }
  return launcherPath;
}

/**
 * Resolve the adapter script for a new agent. Prefers the stable launcher; if it cannot be
 * written, falls back to the current runtime's own adapter, which works until the next runtime
 * replacement.
 *
 * @param launcher The pending result of `ensureAgentAdapterLauncher` for this plugin start.
 */
export async function resolveAgentAdapterPath(
  paseoHome: string,
  launcher: Promise<string>,
): Promise<string> {
  try {
    return await launcher;
  } catch (error) {
    console.error("Shared Browser adapter launcher is unavailable; pinning this agent", error);
    return join(resolveBrowserRuntimeRoot(paseoHome), ADAPTER_FILE);
  }
}
